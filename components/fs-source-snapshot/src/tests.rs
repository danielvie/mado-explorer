// The only write-access native handle is test-only and guarded by an owned fixture.
// This is an aligned mount-point REPARSE_DATA_BUFFER, with bounded UTF-16 path storage.
#[repr(C)]
struct JunctionBuffer {
    tag: u32,
    data_len: u16,
    reserved: u16,
    substitute_offset: u16,
    substitute_len: u16,
    print_offset: u16,
    print_len: u16,
    path: [u16; 1024],
}
fn junction(owner: &Fixture, leaf: &Path, target_owner: &Fixture, target: &Path) {
    use windows_sys::Win32::{
        Foundation::GENERIC_WRITE,
        System::{IO::DeviceIoControl, Ioctl::FSCTL_SET_REPARSE_POINT},
    };
    owner.guard_path(leaf);
    target_owner.guard_path(target);
    assert!(target.is_dir());
    let target_units: Vec<_> = target.as_os_str().encode_wide().collect();
    assert!(drive(&target_units));
    let substitute: Vec<_> = [92, 63, 63, 92]
        .into_iter()
        .chain(target_units.iter().copied())
        .collect();
    let print_offset = substitute.len() + 1;
    let count = print_offset + target_units.len() + 1;
    assert!(count <= 1024);
    let mut buffer = JunctionBuffer {
        tag: 0xa0000003,
        data_len: (8 + count * 2) as u16,
        reserved: 0,
        substitute_offset: 0,
        substitute_len: (substitute.len() * 2) as u16,
        print_offset: (print_offset * 2) as u16,
        print_len: (target_units.len() * 2) as u16,
        path: [0; 1024],
    };
    buffer.path[..substitute.len()].copy_from_slice(&substitute);
    buffer.path[print_offset..print_offset + target_units.len()].copy_from_slice(&target_units);
    let name = admitted_name(leaf).unwrap();
    // SAFETY: only this test's owned empty directory receives a bounded junction buffer.
    let raw = unsafe {
        CreateFileW(
            name.as_ptr(),
            GENERIC_WRITE,
            FILE_SHARE_READ | FILE_SHARE_WRITE | FILE_SHARE_DELETE,
            ptr::null(),
            OPEN_EXISTING,
            FILE_FLAG_OPEN_REPARSE_POINT | FILE_FLAG_BACKUP_SEMANTICS,
            ptr::null_mut(),
        )
    };
    assert_ne!(raw, INVALID_HANDLE_VALUE, "{}", io::Error::last_os_error());
    let handle = unsafe { OwnedHandle::from_raw_handle(raw) };
    let mut returned = 0;
    let ok = unsafe {
        DeviceIoControl(
            handle.as_raw_handle(),
            FSCTL_SET_REPARSE_POINT,
            (&buffer as *const JunctionBuffer).cast(),
            8 + buffer.data_len as u32,
            ptr::null_mut(),
            0,
            &mut returned,
            ptr::null_mut(),
        )
    };
    assert_ne!(ok, 0, "{}", io::Error::last_os_error());
}

#[test]
fn owned_nonprivileged_junction_captures_leaf_even_with_missing_target() {
    let source = Fixture::new();
    let external = Fixture::new();
    let target = external.directory("target");
    let sentinel = external.file("target-sentinel");
    let leaf = source.directory("junction");
    junction(&source, &leaf, &external, &target);
    let target_snapshot = Snapshot::capture(target.clone()).unwrap();
    let leaf_snapshot = Snapshot::capture(leaf.clone()).unwrap();
    assert_eq!(
        leaf_snapshot.kind(),
        EntryKind::ReparsePoint { tag: 0xa0000003 }
    );
    assert_ne!(leaf_snapshot.identity(), target_snapshot.identity());
    leaf_snapshot.revalidate_original_name().unwrap();
    drop(target_snapshot);
    external.remove_dir(&target);
    // If capture followed the final entry, this would fail because its target is now absent.
    assert_eq!(
        Snapshot::capture(leaf.clone()).unwrap().identity(),
        leaf_snapshot.identity()
    );
    leaf_snapshot.revalidate_original_name().unwrap();
    source.remove_dir(&leaf);
    assert!(matches!(
        leaf_snapshot.revalidate_original_name(),
        Err(SnapshotError::Missing)
    ));
    drop(leaf_snapshot);
    assert!(Snapshot::capture(sentinel).is_ok());
    external.guard();
}

#[test]
#[ignore = "Requires separately authorized symlink privilege; generated fixtures only, no elevation/bypass"]
fn privileged_symlink_leaf_nonfollowing_manual_pending() {
    let f = Fixture::new();
    let target = f.file("target");
    let leaf = f.path("symlink");
    f.guard_path(&leaf);
    std::os::windows::fs::symlink_file(&target, &leaf).unwrap();
    let snapshot = Snapshot::capture(leaf.clone()).unwrap();
    assert_eq!(snapshot.kind(), EntryKind::ReparsePoint { tag: 0xa000000c });
    assert_ne!(
        snapshot.identity(),
        Snapshot::capture(target.clone()).unwrap().identity()
    );
    f.remove_file(&target);
    snapshot.revalidate_original_name().unwrap();
    f.remove_file(&leaf);
}
